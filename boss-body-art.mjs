// Design in the shared 40 × 36 coordinate space. The modular bodies render
// on a denser pixel grid so diagonal edges can take smaller steps.
function paintLayers(canvas, layers) {
  const ctx = canvas.getContext('2d');
  ctx.save();
  ctx.scale(canvas.width / 40, canvas.height / 36);
  for (const [color, shape] of layers) {
    ctx.fillStyle = color;
    if (typeof shape === 'string') ctx.fill(new Path2D(shape));
    else for (const rect of shape) ctx.fillRect(...rect);
  }
  ctx.restore();
}

