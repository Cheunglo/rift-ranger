// The shared 40 × 36 pixel grid leaves room for each body's outline and limbs.
function paintLayers(canvas, layers) {
  const ctx = canvas.getContext('2d');
  for (const [color, rectangles] of layers) {
    ctx.fillStyle = color;
    for (const rect of rectangles) ctx.fillRect(...rect);
  }
}

